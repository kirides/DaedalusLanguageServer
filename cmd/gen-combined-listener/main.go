// gen-combined-listener generates langserver/combined_listener.go from the
// DaedalusListener interface in daedalus/parser/daedalus_listener.go.
//
// Run it from the langserver directory (see go:generate in combined_listener.go).
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
)

func main() {
	in := filepath.Join("..", "daedalus", "parser", "daedalus_listener.go")
	out := "combined_listener.go"

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, in, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	var ruleMethods []string // EnterX / ExitX with their context type
	types := map[string]string{}
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "DaedalusListener" {
			return true
		}
		for _, m := range ts.Type.(*ast.InterfaceType).Methods.List {
			if len(m.Names) != 1 {
				continue // embedded antlr.ParseTreeListener
			}
			fn := m.Type.(*ast.FuncType)
			star := fn.Params.List[0].Type.(*ast.StarExpr)
			ruleMethods = append(ruleMethods, m.Names[0].Name)
			types[m.Names[0].Name] = star.X.(*ast.Ident).Name
		}
		return false
	})

	var b bytes.Buffer
	b.WriteString(`// Code generated by cmd/gen-combined-listener; DO NOT EDIT.

package langserver

import (
	"github.com/kirides/DaedalusLanguageServer/daedalus/parser"

	"github.com/antlr4-go/antlr/v4"
)

// combineListeners returns a listener that forwards to all given listeners.
func combineListeners(listeners ...parser.DaedalusListener) parser.DaedalusListener {
	if len(listeners) == 1 {
		return listeners[0]
	}

	var current parser.DaedalusListener
	for i := 0; i < len(listeners); i++ {
		if listeners[i] == nil {
			continue
		}
		if current == nil {
			current = listeners[i]
		} else {
			current = &CombinedDaedalusListener{left: current, right: listeners[i]}
		}
	}
	return current
}

// CombinedDaedalusListener forwards every event to both listeners.
type CombinedDaedalusListener struct {
	left, right parser.DaedalusListener
}

func (l *CombinedDaedalusListener) EnterEveryRule(ctx antlr.ParserRuleContext) {
	l.left.EnterEveryRule(ctx)
	l.right.EnterEveryRule(ctx)
}

func (l *CombinedDaedalusListener) ExitEveryRule(ctx antlr.ParserRuleContext) {
	l.left.ExitEveryRule(ctx)
	l.right.ExitEveryRule(ctx)
}

func (l *CombinedDaedalusListener) VisitErrorNode(node antlr.ErrorNode) {
	l.left.VisitErrorNode(node)
	l.right.VisitErrorNode(node)
}

func (l *CombinedDaedalusListener) VisitTerminal(node antlr.TerminalNode) {
	l.left.VisitTerminal(node)
	l.right.VisitTerminal(node)
}
`)
	for _, name := range ruleMethods {
		fmt.Fprintf(&b, "\nfunc (l *CombinedDaedalusListener) %s(c *parser.%s) {\n\tl.left.%s(c)\n\tl.right.%s(c)\n}\n", name, types[name], name, name)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
